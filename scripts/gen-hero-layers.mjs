import { readFileSync, writeFileSync } from "node:fs";

const SPEC = "docs/specs/v2/desktop-view/FYT - Landing Page.css";
const css = readFileSync(SPEC, "utf8").split(/\r?\n/);

const blocks = [];
let cur = null;
for (const ln of css) {
  const m = ln.match(/^\s*\/\* (.+?) \*\/\s*$/);
  if (m) { if (cur) blocks.push(cur); cur = { name: m[1], lines: [] }; }
  else if (cur) cur.lines.push(ln);
}
if (cur) blocks.push(cur);

const names = blocks.map((b) => b.name);
const prop = (b, key) => {
  for (const l of b.lines) {
    const t = l.trim();
    if (t.startsWith(key + ":")) return t.slice(key.length + 1).trim().replace(/;$/, "").trim();
  }
  return null;
};
const firstIdx = (n) => names.indexOf(n);

function vectorsBetween(startName, endName) {
  const a = firstIdx(startName);
  const b = endName ? firstIdx(endName) : blocks.length;
  const out = [];
  for (let i = a + 1; i < b; i++) {
    if (blocks[i].name === "Vector") {
      out.push({
        left: prop(blocks[i], "left"),
        right: prop(blocks[i], "right"),
        top: prop(blocks[i], "top"),
        bottom: prop(blocks[i], "bottom"),
        background: prop(blocks[i], "background"),
      });
    }
  }
  return out;
}

const cone = vectorsBetween("Base cone", "Rays")[0];
const rays = vectorsBetween("Rays", "Dust");
const dust = vectorsBetween("Dust", "Top bloom");
const bloomB = blocks[firstIdx("Top bloom")];
const bloom = {
  width: prop(bloomB, "width"), height: prop(bloomB, "height"),
  left: prop(bloomB, "left"), top: prop(bloomB, "top"),
  background: prop(bloomB, "background"), filter: prop(bloomB, "filter"),
};
const vig = vectorsBetween("Vignette", "Text scrim").map((v) => v.background);
const scrimB = blocks[firstIdx("Text scrim")];
const scrim = {
  width: prop(scrimB, "width"), height: prop(scrimB, "height"),
  left: prop(scrimB, "left"), top: prop(scrimB, "top"),
  background: prop(scrimB, "background"), filter: prop(scrimB, "filter"),
};

const banner = "// AUTO-GENERATED by scripts/gen-hero-layers.mjs — do not edit by hand.\n";
const out =
  banner +
  `export type Inset = { left: string; right: string; top: string; bottom: string; background: string };\n` +
  `export const HERO_CONE: Inset = ${JSON.stringify(cone, null, 2)};\n` +
  `export const HERO_RAYS: Inset[] = ${JSON.stringify(rays, null, 2)};\n` +
  `export const HERO_DUST: Inset[] = ${JSON.stringify(dust, null, 2)};\n` +
  `export const HERO_BLOOM = ${JSON.stringify(bloom, null, 2)} as const;\n` +
  `export const HERO_VIGNETTE: string[] = ${JSON.stringify(vig, null, 2)};\n` +
  `export const HERO_SCRIM = ${JSON.stringify(scrim, null, 2)} as const;\n`;

writeFileSync("src/app/heroLayers.ts", out);
console.log(`Wrote src/app/heroLayers.ts — rays=${rays.length} dust=${dust.length} vignette=${vig.length}`);
