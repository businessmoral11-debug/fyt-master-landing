#!/usr/bin/env node
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const __dirname = dirname(fileURLToPath(import.meta.url));
const OUTPUT_PATH = join(__dirname, "..", "src", "app", "data", "worldMapContinents.ts");

const landTopology = require("world-atlas/land-110m.json");
const landFeature = feature(landTopology, landTopology.objects.land);
const geometry = landFeature.type === "FeatureCollection" ? landFeature.features[0].geometry : landFeature.geometry;
const polygons = geometry.type === "MultiPolygon" ? geometry.coordinates : [geometry.coordinates];

const WIDTH = 1264;
const HEIGHT = 632;
function project([lon, lat]) {
  const x = ((lon + 180) / 360) * WIDTH;
  const y = ((90 - lat) / 180) * HEIGHT;
  return [Math.round(x * 10) / 10, Math.round(y * 10) / 10];
}

function ringToPath(ring) {
  let d = "";
  let prevX = null;
  for (const point of ring) {
    const [x, y] = project(point);
    if (prevX === null || Math.abs(x - prevX) > WIDTH / 2) {
      d += `M${x},${y}`;
    } else {
      d += `L${x},${y}`;
    }
    prevX = x;
  }
  return d + "Z";
}

let d = "";
let totalPoints = 0;
for (const polygon of polygons) {
  for (const ring of polygon) {
    if (ring.length < 3) continue;
    d += ringToPath(ring);
    totalPoints += ring.length;
  }
}

const output = `// Generated by scripts/generate-world-map-continents.mjs from world-atlas's
export const WORLD_MAP_CONTINENTS_PATH =
  "${d}";
`;

writeFileSync(OUTPUT_PATH, output);
console.log(`Wrote continents path (${d.length} chars, ${totalPoints} points) to ${OUTPUT_PATH}`);
